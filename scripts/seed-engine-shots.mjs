/* global process, console, Buffer, URL */
/**
 * Seeds a scratch profile plus the throwaway PostgreSQL 17 and MariaDB 11 test
 * servers for the engine screenshots (steps 40* and 41* of src/main/screenshots.ts):
 *
 *   node scripts/seed-engine-shots.mjs
 *   npm run build
 *   VORTAQ_USER_DATA=$TMPDIR/vortaq-engine-shots/profile VORTAQ_PLAIN_SECRETS=1 \
 *   VORTAQ_AI_FIXTURE=1 VORTAQ_SCREENSHOTS=$TMPDIR/vortaq-engine-shots VORTAQ_SHOTS_ONLY=40,41 npx electron .
 *
 * Env: VORTAQ_SHOTS_ENGINE_PROFILE (scratch profile, wiped; must end in /profile),
 * VORTAQ_TEST_PG_URL, VORTAQ_TEST_MARIADB_URL (default: the compose containers).
 * Never touches ports 3306-3309 or 5432 and never the real profile.
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'
import mysql from 'mysql2/promise'
import pg from 'pg'

const env = (name) => process.env[`VORTAQ_${name}`] ?? process.env[`ELECTRONDB_${name}`]
const PROFILE = resolve(
  env('SHOTS_ENGINE_PROFILE') ||
    join(process.env.TMPDIR || '/tmp', 'vortaq-engine-shots', 'profile')
)
const PG_URL = new URL(
  env('TEST_PG_URL') || 'postgres://postgres:navidog@127.0.0.1:55432/navidog_test'
)
const MARIA_URL = new URL(
  env('TEST_MARIADB_URL') || 'mysql://root:navidog@127.0.0.1:33311/navidog_test'
)

for (const u of [PG_URL, MARIA_URL]) {
  const port = Number(u.port)
  if ((port >= 3306 && port <= 3309) || port === 5432) {
    console.error(`Refusing to seed a server on port ${port}: use the throwaway test containers.`)
    process.exit(1)
  }
}
if (basename(PROFILE) !== 'profile') {
  console.error(
    `Refusing to wipe ${PROFILE}: the scratch profile directory must be named "profile".`
  )
  process.exit(1)
}

/* ---------- servers ---------- */

const PG_DB = decodeURIComponent(PG_URL.pathname.replace(/^\//, '')) || 'postgres'
const client = new pg.Client({
  host: PG_URL.hostname,
  port: Number(PG_URL.port),
  user: decodeURIComponent(PG_URL.username),
  password: decodeURIComponent(PG_URL.password),
  database: PG_DB
})
await client.connect()
await client.query(`
  DROP SCHEMA IF EXISTS tienda CASCADE;
  CREATE SCHEMA tienda;
  CREATE TYPE tienda.estado AS ENUM ('pendiente', 'pagado', 'cancelado');
  CREATE TABLE tienda.clientes (
    id serial PRIMARY KEY,
    nombre text NOT NULL,
    email text UNIQUE,
    etiquetas text[],
    preferencias jsonb,
    alta timestamptz DEFAULT now()
  );
  COMMENT ON TABLE tienda.clientes IS 'Clientes de la tienda';
  CREATE TABLE tienda.pedidos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id integer NOT NULL REFERENCES tienda.clientes (id),
    estado tienda.estado NOT NULL DEFAULT 'pendiente',
    total numeric(10,2) NOT NULL DEFAULT 0,
    creado date NOT NULL DEFAULT current_date
  );
  CREATE INDEX pedidos_cliente_idx ON tienda.pedidos (cliente_id);
  INSERT INTO tienda.clientes (nombre, email, etiquetas, preferencias, alta) VALUES
    ('Ana Torres', 'ana@example.test', '{vip,newsletter}', '{"idioma": "es", "avisos": true}', '2026-09-01 10:15:00+00'),
    ('Bruno Díaz', 'bruno@example.test', '{newsletter}', '{"idioma": "es"}', '2026-09-03 08:40:00+00'),
    ('Carla Méndez', 'carla@example.test', NULL, NULL, '2026-09-10 17:05:00+00'),
    ('Diego Ruiz', 'diego@example.test', '{mayorista}', '{"descuento": 12.5}', '2026-09-18 12:00:00+00'),
    ('Elena Sanz', 'elena@example.test', '{}', '{"idioma": "ca"}', '2026-10-02 09:30:00+00');
  INSERT INTO tienda.pedidos (cliente_id, estado, total, creado) VALUES
    (1, 'pagado', 120.50, '2026-09-02'), (1, 'pendiente', 42.00, '2026-10-01'),
    (2, 'pagado', 19.99, '2026-09-04'), (3, 'cancelado', 75.00, '2026-09-11'),
    (4, 'pagado', 980.00, '2026-09-20'), (5, 'pendiente', 15.30, '2026-10-03');
  CREATE VIEW tienda.v_pendientes AS
    SELECT p.id, c.nombre, p.total FROM tienda.pedidos p JOIN tienda.clientes c ON c.id = p.cliente_id
     WHERE p.estado = 'pendiente';
  CREATE MATERIALIZED VIEW tienda.mv_ventas AS
    SELECT estado, count(*) AS pedidos, sum(total) AS importe FROM tienda.pedidos GROUP BY estado;
  CREATE FUNCTION tienda.total_cliente(cliente integer) RETURNS numeric LANGUAGE sql STABLE AS
    $$ SELECT coalesce(sum(total), 0) FROM tienda.pedidos WHERE cliente_id = cliente $$;
  CREATE SEQUENCE tienda.facturas START 1000;
  CREATE TABLE tienda.ventas (id bigint, fecha date NOT NULL, zona text NOT NULL, importe numeric(10,2))
    PARTITION BY RANGE (fecha);
  CREATE TABLE tienda.ventas_2025 PARTITION OF tienda.ventas
    FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
  CREATE TABLE tienda.ventas_2026 PARTITION OF tienda.ventas
    FOR VALUES FROM ('2026-01-01') TO ('2027-01-01') PARTITION BY LIST (zona);
  CREATE TABLE tienda.ventas_2026_norte PARTITION OF tienda.ventas_2026 FOR VALUES IN ('norte');
  CREATE TABLE tienda.ventas_2026_sur PARTITION OF tienda.ventas_2026 FOR VALUES IN ('sur');
  CREATE TABLE tienda.ventas_otras PARTITION OF tienda.ventas DEFAULT;
  INSERT INTO tienda.ventas VALUES
    (1, '2025-11-03', 'norte', 310.00), (2, '2026-01-15', 'norte', 120.50),
    (3, '2026-02-02', 'sur', 89.90), (4, '2026-03-21', 'sur', 1450.00), (5, '2027-05-01', 'este', 42.00);
`)
// A second database for «Cerrar base de datos» (CREATE DATABASE cannot run in a transaction).
await client.query('DROP DATABASE IF EXISTS tienda_archivo')
await client.query('CREATE DATABASE tienda_archivo')
await client.end()

const maria = await mysql.createConnection({
  host: MARIA_URL.hostname,
  port: Number(MARIA_URL.port),
  user: decodeURIComponent(MARIA_URL.username),
  password: decodeURIComponent(MARIA_URL.password),
  multipleStatements: true
})
await maria.query(`
  DROP DATABASE IF EXISTS shots_maria;
  CREATE DATABASE shots_maria;
  USE shots_maria;
  CREATE TABLE precios (
    id INT PRIMARY KEY,
    producto VARCHAR(40) NOT NULL DEFAULT 'sin nombre',
    importe DECIMAL(10,2) NOT NULL,
    nota VARCHAR(40) INVISIBLE DEFAULT 'interna'
  ) WITH SYSTEM VERSIONING;
  INSERT INTO precios (id, producto, importe) VALUES (1, 'Café', 1.20), (2, 'Té', 1.10), (3, 'Zumo', 2.50);
  UPDATE precios SET importe = 1.30 WHERE id = 1;
  CREATE TABLE clientes (id INT AUTO_INCREMENT PRIMARY KEY, nombre VARCHAR(40));
  CREATE SEQUENCE seq_facturas START WITH 500;
  CREATE SEQUENCE seq_tickets START WITH 1 INCREMENT BY 10 CYCLE;
  CREATE TABLE catalogo (
    id UUID NOT NULL DEFAULT uuid() PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL,
    ficha JSON NULL,
    servidor INET6 NULL,
    red INET4 NULL
  );
`)
await maria.end()

/* ---------- profile ---------- */

rmSync(PROFILE, { recursive: true, force: true })
mkdirSync(PROFILE, { recursive: true })
const iso = new Date().toISOString()
const base = {
  color: null,
  savePassword: true,
  customDatabases: [],
  initialQueries: '',
  ssh: {
    enabled: false,
    host: '',
    port: 22,
    username: '',
    authType: 'password',
    savePassword: false
  },
  backupDir: join(PROFILE, 'backups'),
  extraBackupDirs: [],
  createdAt: iso,
  updatedAt: iso
}
const connections = [
  {
    ...base,
    id: 'shot-pg',
    name: 'PostgreSQL Local',
    color: '#60a5fa',
    environment: 'local',
    engine: 'postgresql',
    host: PG_URL.hostname,
    port: Number(PG_URL.port),
    username: decodeURIComponent(PG_URL.username),
    ssl: { enabled: false, verifyServer: false, mode: 'prefer' },
    network: { connectTimeoutMs: 10000, keepAliveSec: 60 },
    postgres: {
      initialDatabase: PG_DB,
      showSystemSchemas: false,
      timeZone: 'Europe/Madrid',
      searchPath: ''
    }
  },
  {
    ...base,
    id: 'shot-maria',
    name: 'MariaDB Local',
    color: '#a78bfa',
    environment: 'local',
    engine: 'mariadb',
    host: MARIA_URL.hostname,
    port: Number(MARIA_URL.port),
    username: decodeURIComponent(MARIA_URL.username),
    ssl: { enabled: false, verifyServer: false }
  }
]
const b64 = (s) => Buffer.from(s, 'utf8').toString('base64')
const write = (name, data) =>
  writeFileSync(join(PROFILE, name), JSON.stringify(data, null, 2), { mode: 0o600 })
write('connections.json', { version: 1, items: connections })
write('credentials.json', {
  version: 1,
  codec: 'plain',
  items: {
    'mysql:shot-pg': b64(decodeURIComponent(PG_URL.password)),
    'mysql:shot-maria': b64(decodeURIComponent(MARIA_URL.password)),
    // Fake key for the AI screens (answered by VORTAQ_AI_FIXTURE, never sent anywhere).
    'ai:shot-ai-claude': b64('sk-ant-fixture-not-a-real-key')
  }
})
write('settings.json', {
  previewEngines: true,
  theme: 'dark',
  checkUpdatesOnStartup: false,
  aiEnabled: true,
  aiDefaultProviderId: 'shot-ai-claude'
})
write('ai-providers.json', {
  version: 1,
  items: [
    {
      id: 'shot-ai-claude',
      name: 'Claude',
      type: 'anthropic',
      baseUrl: '',
      model: 'claude-opus-5-5',
      createdAt: iso,
      updatedAt: iso
    }
  ]
})
console.log(`Seeded ${PROFILE} (PostgreSQL schema tienda, MariaDB database shots_maria)`)
